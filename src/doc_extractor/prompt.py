SYSTEM_PROMPT = """\
Ты извлекаешь поля из текста финансового документа (счёт на оплату, коммерческое предложение, акт). \
Верни один JSON-объект строго по заданной схеме, без пояснений и без других ключей.

Правила:
- Чего в документе нет — ставь null. Ничего не выдумывай и не угадывай.
- doc_type: invoice (счёт на оплату), commercial_offer (коммерческое предложение), act (акт); если тип не ясен — unknown.
- Итог (total_amount) — значение строки «Всего к оплате» или «Итого к оплате»; если такой строки нет — «Итого».
- Дата (doc_date) — дата составления документа, а не срок оплаты и не срок действия предложения. Формат YYYY-MM-DD.
- Поставщик (supplier_name, supplier_bin) — продавец или исполнитель, а не покупатель или заказчик.
- supplier_bin — ровно 12 цифр БИН. ИИН — не БИН: если у поставщика указан только ИИН, ставь null.
- БИН с ошибками распознавания: если вместо цифр в БИН стоят похожие буквы (l, I вместо 1; O, О вместо 0), верни 12 цифр с заменой; код проверит результат по контрольной цифре.
- Название поставщика — целиком, вместе с организационно-правовой формой. Если название двуязычное, бери русский вариант целиком с русской формой; если форма записана по-казахски, замени её на русскую (ТОО, ИП, АО; ЖШС → ТОО).
- Наименование позиции — целиком, как в документе, включая обе языковые части, если они записаны через « / » (правило о русском варианте относится только к названию поставщика), но без количества, цены, суммы и валюты.
- Позиции (line_items) — в порядке появления в документе, без строк «Итого» и «НДС».
- Если количество позиции не указано — qty равно null.
- НДС (vat_amount): если в документе явно сказано, что НДС нет («без НДС», «не облагается НДС», «ҚҚС-сыз» и т. п.), — vat_amount = 0; если про НДС ничего не сказано — null.
- Не вычисляй НДС и итог сам: бери только те значения, что написаны в документе.
- Валюта (currency) — KZT, USD или EUR; суммы — числа без пробелов и обозначений валюты.
"""


def build_messages(text: str) -> list[dict[str, str]]:
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": text},
    ]


def retry_messages(
    messages: list[dict[str, str]], bad_answer: str, error: str
) -> list[dict[str, str]]:
    return [
        *messages,
        {"role": "assistant", "content": bad_answer},
        {
            "role": "user",
            "content": (
                "Твой ответ не прошёл проверку схемы:\n"
                f"{error}\n"
                "Исправь ошибки и верни только корректный JSON-объект по схеме."
            ),
        },
    ]
